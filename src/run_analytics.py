"""Command-line entry point for analytics on standardized MySQL data."""

import argparse
from pathlib import Path

import pandas as pd

from .analytics import calculate
from .config import settings
from .database import DatabaseClient
from .reporting import create_report


def run(display_date=None, display_limit=10, persist=False, report=False):
    """Read standardized SQL data, run analytics, and print compact results."""
    cfg = settings()
    database = DatabaseClient(cfg)

    # 1. Read calculation-ready data from MySQL without re-ingesting raw files.
    data = database.read_standardized()

    # 2. Run pricing, P&L attribution, VaR/backtesting and stress testing.
    frames = calculate(
        cfg,
        data["position_daily"],
        data["market_data_daily"],
        data["nav_daily"],
        data["actual_pnl_daily"],
        data["transaction_daily"],
    )
    instrument_risk, pnl, portfolio_summary, stress = frames

    # 3. Display one requested date, or the latest available business date.
    selected_date = display_date or str(
        pd.to_datetime(portfolio_summary["business_date"]).max().date()
    )
    print(f"\nAnalytics completed. Display date: {selected_date}")
    for name, frame in {
        "Instrument risk": instrument_risk,
        "P&L attribution": pnl,
        "VaR and backtesting": portfolio_summary,
        "Stress testing": stress,
    }.items():
        selected = frame[
            pd.to_datetime(frame["business_date"]).dt.strftime("%Y-%m-%d")
            == selected_date
        ]
        print(f"\n--- {name} ({len(selected)} rows; showing up to {display_limit}) ---")
        print(selected.head(display_limit).to_string(index=False))

    # 4. Print the pricing validation generated by calculate().
    output = Path(cfg["root"]) / cfg["paths"]["processed"]
    validation = pd.read_csv(output / "pricing_validation.csv")
    print("\n--- Pricing validation ---")
    print(validation.to_string(index=False))

    # 5. Optionally persist the four analytics outputs without reloading raw data.
    if persist:
        run_id = database.begin_analytics_run()
        rows_written = database.persist_analytics(frames)
        print("\n--- MySQL persistence ---")
        print(f"Analytics run ID: {run_id}")
        print(f"Analytics rows written: {rows_written}")

    # 6. Optionally create the Excel report from the newly generated CSV outputs.
    if report:
        report_path = create_report(cfg, selected_date)
        print("\n--- Excel report ---")
        print(f"Report: {report_path}")

    print(f"\nCSV outputs: {output}")
    return frames


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--date", help="Business date to display after full-history calculations"
    )
    parser.add_argument(
        "--limit", type=int, default=10, help="Maximum displayed rows per output"
    )
    parser.add_argument(
        "--persist", action="store_true",
        help="Write analytics outputs to MySQL without re-ingesting raw data",
    )
    parser.add_argument(
        "--report", action="store_true",
        help="Create the Excel report from the generated analytics CSV files",
    )
    args = parser.parse_args()
    run(args.date, args.limit, args.persist, args.report)


if __name__ == "__main__":
    main()
